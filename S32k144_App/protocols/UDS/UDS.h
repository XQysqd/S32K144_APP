                                         /*!< 物理请求 - CAN 传输层接收物理地址 */
#define TX_RESP_ADDR_ID      (0x6DAu)    /* PhysResp - CAN TP TX physical ID */
                                         /*!< 物理响应 - CAN 传输层发送物理地址 */

#endif /* UDS_H_ */